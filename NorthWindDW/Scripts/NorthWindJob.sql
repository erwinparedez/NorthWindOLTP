		@enabled=1, 
		@notify_level_eventlog=0, 
		@notify_level_email=0, 
		@notify_level_netsend=0, 
		@notify_level_page=0, 
		@delete_level=0, 
		@description=N'NorthWind BI Incremental ETL Job executing star schema packages in sequence.', 
		@category_name=N'[Uncategorized (Local)]', 
